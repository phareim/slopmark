// Scores eval/data/{human,ai}.jsonl with the same classify() the server runs, then reports
// false alarms on human text and hit rate on AI text per threshold. Scores are cached in
// eval/data/scores.jsonl by cache key, so reruns only pay for new passages.
// Usage: node eval/run.mjs [--md]   (--md writes eval/RESULTS.md)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { classify, cacheKey } from '../server/src/classify.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(HERE, 'data');
const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : []);

const REFUSAL = /^(I can['’]?t|I cannot|I won['’]t|I'm sorry|Sorry|Beklager|Jeg kan ikke)/i;
const samples = [
  ...read(path.join(DATA, 'human.jsonl')),
  ...read(path.join(DATA, 'ai.jsonl')).filter((s) => !REFUSAL.test(s.text)),
];
const SCORES = path.join(DATA, 'scores.jsonl');
const scores = new Map(read(SCORES).map((r) => [r.key, r.p_ai]));

const todo = samples.filter((s) => !scores.has(cacheKey(s.text)));
let cursor = 0;
async function worker() {
  while (cursor < todo.length) {
    const s = todo[cursor++];
    const key = cacheKey(s.text);
    try {
      const { p_ai } = await classify(s.text);
      scores.set(key, p_ai);
      fs.appendFileSync(SCORES, JSON.stringify({ key, p_ai }) + '\n');
    } catch (e) {
      console.error('classify failed:', e.message);
    }
  }
}
await Promise.all(Array.from({ length: 6 }, worker));

const scored = samples.map((s) => ({ ...s, p: scores.get(cacheKey(s.text)) })).filter((s) => typeof s.p === 'number');
const human = scored.filter((s) => s.label === 'human');
const ai = scored.filter((s) => s.label === 'ai');

// AUC: chance that a random AI passage scores above a random human one.
let wins = 0;
for (const a of ai) for (const h of human) wins += a.p > h.p ? 1 : a.p === h.p ? 0.5 : 0;
const auc = wins / (ai.length * human.length);

const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : '–');
const rate = (xs, t) => `${pct(xs.filter((s) => s.p >= t).length, xs.length)} (${xs.filter((s) => s.p >= t).length}/${xs.length})`;
const groupBy = (xs, k) => xs.reduce((m, s) => ((m[s[k]] ||= []).push(s), m), {});
const THRESHOLDS = [0.5, 0.8, 0.9, 0.95, 0.98, 0.99];

const lines = [];
const out = (l = '') => lines.push(l);
out(`Samples: ${human.length} human, ${ai.length} AI. AUC ${auc.toFixed(3)}. Model: ${fs.existsSync(SCORES) ? 'jev-latest' : '?'}.`);
out();
out('| threshold | false alarms (human flagged) | hits (AI flagged) |');
out('|---|---|---|');
for (const t of THRESHOLDS) out(`| ${t} | ${rate(human, t)} | ${rate(ai, t)} |`);

const T = Number(process.env.SLOPMARK_THRESHOLD || 0.95);
out();
out(`At threshold ${T}:`);
out();
out('| group | flagged |');
out('|---|---|');
for (const [k, xs] of Object.entries(groupBy(human, 'source'))) out(`| human · ${k} | ${rate(xs, T)} |`);
for (const key of ['style', 'model', 'lang']) {
  for (const [k, xs] of Object.entries(groupBy(ai, key))) out(`| AI · ${key} ${k} | ${rate(xs, T)} |`);
}

const fp = human.filter((s) => s.p >= T).sort((a, b) => b.p - a.p);
if (fp.length) {
  out();
  out('False alarms:');
  for (const s of fp) out(`- ${s.p.toFixed(3)} · ${s.source} · ${s.text.slice(0, 140)}…`);
}

console.log(lines.join('\n'));
if (process.argv.includes('--md')) {
  const header = `# Eval results\n\nGenerated by \`node eval/run.mjs --md\` on ${new Date().toISOString().slice(0, 10)}. Data: see eval/README.md.\n\n`;
  fs.writeFileSync(path.join(HERE, 'RESULTS.md'), header + lines.join('\n') + '\n');
}
